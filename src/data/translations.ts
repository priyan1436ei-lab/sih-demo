export function getLocalizedDiseaseName(disease: string, lang: Language): string {
  if (!disease) return "";
  const match = Object.keys(DISEASE_LOCALIZED_NAMES).find(
    (k) => k.toLowerCase() === disease.toLowerCase() || disease.toLowerCase().includes(k.toLowerCase())
  );
  if (match && DISEASE_LOCALIZED_NAMES[match]?.[lang]) {
    return DISEASE_LOCALIZED_NAMES[match][lang];
  }
  return disease;
}

